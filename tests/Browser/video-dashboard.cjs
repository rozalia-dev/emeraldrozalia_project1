const {createRequire} = require('node:module');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {chromium} = createRequire(path.join(process.env.VIDEO_BROWSER_MODULES,'package.json'))('playwright');
(async () => {
    const browser = await chromium.launch({headless:true});
    const context = await browser.newContext({viewport:{width:1915,height:1128}});
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror',error => errors.push(error.message));
    const base = 'http://127.0.0.1:8000';
    const artifacts = process.env.VIDEO_ARTIFACTS;
    fs.mkdirSync(artifacts,{recursive:true});
    page.setDefaultTimeout(20000);
    try {
        await page.goto(base+'/login');
        await page.locator('#login-email').fill(process.env.ADMIN_EMAIL);
        await page.locator('#login-password').fill(process.env.ADMIN_PASSWORD);
        await Promise.all([page.waitForURL(url => !url.pathname.endsWith('/login')),page.locator('.auth-login form[action$="/login"] button[type=submit]').click()]);
        await page.goto(base+'/admin/resource/videos');
        await page.locator('[data-video-dashboard]').waitFor();
        await page.locator('[data-new-video]').first().click();
        await page.locator('#vd-form [name=title]').fill('Browser Cap Video');
        const productId = await page.locator('#vd-form [name=product_id] option').filter({hasText:'BROWSER-VIDEO-001'}).getAttribute('value');
        await page.locator('#vd-form [name=product_id]').selectOption(productId);
        await page.locator('#vd-files').setInputFiles(process.env.VIDEO_TEST_FILE);
        await page.locator('#vd-form [name=title]').fill('Browser Cap Video');
        await page.locator('#vd-form [name=captions]').setInputFiles(process.env.VIDEO_TEST_CAPTIONS);
        await page.locator('#vd-submit').click();
        await page.locator('.vd-table').getByText('Browser Cap Video',{exact:true}).waitFor();
        assert.match(await page.locator('#vd-notice').innerText(),/saved successfully/);
        const data = JSON.parse(await page.locator('#vd-video-data').textContent());
        const record = data.find(item => item.title==='Browser Cap Video');
        assert.ok(record.poster,'Generated thumbnail is saved');
        assert.ok(record.captions,'Captions are saved');
        assert.equal(record.status,'draft');
        assert.equal(record.resolution,'320 x 180');
        assert.ok(record.duration>0,'Duration is extracted');
        await page.locator('[data-select-video="'+record.id+'"]').first().click();
        await page.waitForFunction(() => document.querySelector('#vd-preview video')?.readyState>=2);
        const visitor = await browser.newContext();
        assert.equal((await visitor.request.get(record.playback)).status(),404,'Draft cannot be downloaded anonymously');
        await page.screenshot({path:path.join(artifacts,'videos-desktop.png'),fullPage:true});
        await page.locator('#vd-settings-form [name=description]').fill('Updated through the accessibility panel.');
        await page.locator('#vd-settings-form button[type=submit]').last().click();
        await page.waitForFunction(() => document.querySelector('#vd-notice')?.textContent.includes('settings saved'));
        await page.locator('[data-edit-video="'+record.id+'"]').click();
        await page.locator('#vd-form [name=status]').selectOption('published');
        await page.locator('#vd-form [name=visibility]').selectOption('public');
        await page.locator('#vd-submit').click();
        await page.waitForFunction(() => JSON.parse(document.querySelector('#vd-video-data').textContent).some(v=>v.title==='Browser Cap Video' && v.status==='published'));
        const asset = await visitor.request.get(record.playback,{headers:{Range:'bytes=0-31'}});
        assert.equal(asset.status(),206,'Native player supports range requests');
        assert.equal((await visitor.request.get(record.captions)).headers()['content-type'],'text/vtt; charset=UTF-8');
        const storefront = await visitor.newPage();
        await storefront.goto(base+'/product/browser-video-cap');
        assert.ok(await storefront.locator('[data-er-video]').count(),'Published video appears in product gallery');
        await storefront.locator('[data-er-video]').evaluate(video => { video.muted=true; return video.play(); });
        await storefront.waitForTimeout(3200);
        await page.goto(base+'/admin/resource/videos');
        const measured = JSON.parse(await page.locator('#vd-video-data').textContent()).find(v=>v.id===record.id);
        assert.equal(measured.views,1,'Public playback records one view');
        await page.locator('#vd-audit').click();
        await page.locator('#vd-info-dialog[open]').getByText('video.created',{exact:true}).waitFor();
        await page.locator('[data-close-info]').first().click();
        await page.locator('#vd-filters [name=q]').fill('Does not exist 123');
        await Promise.all([page.waitForURL(/q=/),page.locator('#vd-filters button[type=submit]').click()]);
        await page.getByText('No videos match your filters',{exact:true}).waitFor();
        await page.locator('.vd-reset').click();
        await page.locator('.vd-table').getByText('Browser Cap Video',{exact:true}).waitFor();
        await page.setViewportSize({width:390,height:844});
        await page.screenshot({path:path.join(artifacts,'videos-mobile.png'),fullPage:true});
        const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth+1);
        assert.equal(overflow,false,'Mobile document must not overflow horizontally');
        await page.locator('[data-new-video]').first().click();
        assert.ok(await page.locator('#vd-dialog').isVisible(),'Upload dialog opens on mobile');
        await page.locator('[data-close-dialog]').first().click();
        await page.setViewportSize({width:1440,height:1000});
        await page.locator('.vd-row-check[value="'+record.id+'"]').check();
        page.once('dialog',dialog => dialog.accept());
        await page.locator('[data-bulk-action=draft]').click();
        await page.waitForFunction(() => JSON.parse(document.querySelector('#vd-video-data').textContent).some(v=>v.title==='Browser Cap Video' && v.status==='draft'));
        assert.equal((await visitor.request.get(record.playback)).status(),404,'Unpublishing revokes public access');
        const downloadPromise = page.waitForEvent('download');
        await page.locator('.vd-quick-actions a[href*="/videos/export"]').click();
        const download = await downloadPromise;
        assert.match(download.suggestedFilename(),/^videos-.*\.csv$/);
        await page.locator('[data-delete-video="'+record.id+'"]').waitFor();
        page.once('dialog',dialog => dialog.accept());
        await page.locator('[data-delete-video="'+record.id+'"]').click();
        await page.waitForFunction(() => !document.querySelector('.vd-table')?.textContent.includes('Browser Cap Video'));
        assert.equal((await context.request.get(record.playback)).status(),404,'Deleted file is no longer accessible');
        assert.deepEqual(errors,[],'No browser JavaScript errors');
        await visitor.close();
        console.log('Video browser checks passed: login, upload, thumbnail, captions, preview, settings, publishing, public playback, analytics, audit, search, mobile layout, bulk draft, export and deletion.');
    } catch (error) {
        await page.screenshot({path:path.join(artifacts,'videos-failure.png'),fullPage:true}).catch(()=>{});
        console.error('Browser failure URL:',page.url());
        console.error('Form errors:',await page.locator('#vd-form-errors').textContent().catch(()=>'unavailable'));
        throw error;
    } finally { await browser.close(); }
})().catch(error => {console.error(error);process.exitCode=1;});
